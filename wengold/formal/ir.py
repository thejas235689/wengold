"""Property IR — a small, typed description of what is to be proven.

A property is written once and consumed by every backend: compiled to SystemVerilog
assertions for SymbiYosys, and to the in-process engines (explicit-state and z3).
Keeping it in one IR is what lets the same claim be checked by more than one
engine and cross-checked.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from enum import Enum


class PropertyKind(str, Enum):
    SAFETY = "safety"      # assert always P holds in every reachable state
    COVER = "cover"        # is P reachable at all
    ASSUME = "assume"      # constrain the environment (an input assumption)


@dataclass(frozen=True)
class Property:
    name: str
    expr: str
    kind: PropertyKind = PropertyKind.SAFETY
    clock: str | None = None
    reset: str | None = None
    depth: int | None = None
    module: str | None = None
    source: str = "generated"      # where the property came from

    @classmethod
    def safety(cls, name: str, expr: str, **kw) -> "Property":
        return cls(name, expr, PropertyKind.SAFETY, **kw)

    @classmethod
    def cover(cls, name: str, expr: str, **kw) -> "Property":
        return cls(name, expr, PropertyKind.COVER, **kw)

    @classmethod
    def assume(cls, name: str, expr: str, **kw) -> "Property":
        return cls(name, expr, PropertyKind.ASSUME, **kw)

    def to_sva(self) -> str:
        clk = self.clock or "clk"
        guard = f" disable iff (!{self.reset})" if self.reset else ""
        if self.kind is PropertyKind.SAFETY:
            body = f"assert property (@(posedge {clk}){guard} {self.expr});"
        elif self.kind is PropertyKind.COVER:
            body = f"cover property (@(posedge {clk}){guard} {self.expr});"
        else:
            body = f"assume property (@(posedge {clk}){guard} {self.expr});"
        return f"a_{self.name}: {body}"

    def as_dict(self) -> dict:
        return {"name": self.name, "expr": self.expr, "kind": self.kind.value,
                "clock": self.clock, "reset": self.reset, "depth": self.depth,
                "module": self.module, "source": self.source}

    def digest(self) -> str:
        return "sha256:" + hashlib.sha256(
            json.dumps(self.as_dict(), sort_keys=True).encode()).hexdigest()[:16]


def sva_module(module: str, properties: list[Property]) -> str:
    """Compile a set of properties into a bindable SystemVerilog assertion module."""
    lines = [f"// generated by WENGOLD — properties for {module}", f"module {module}_props;"]
    for p in properties:
        lines.append("    " + p.to_sva())
    lines.append("endmodule")
    return "\n".join(lines) + "\n"
