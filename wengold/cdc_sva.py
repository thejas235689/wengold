@dataclass
class Decl:
    signal: str
    direction: str = "input"
    msb: int | None = None
    lsb: int | None = None
    width_param: bool = False

    def render(self) -> str:
        if self.msb is not None:
            return f"  {self.direction} logic [{self.msb}:{self.lsb}] {self.signal}"
        if self.width_param:
            return f"  {self.direction} logic [{self.signal.upper()}_W-1:0] {self.signal}"
        return f"  {self.direction} logic {self.signal}"


def _add_decl(decls: dict, port: Port, sigmap: dict) -> Decl:
    """Record the declaration for `port`'s signal, merging ranges."""
    sig = sigmap[port.base_name]
    d = decls.get(sig)
    if d is None:
        d = Decl(signal=sig, direction=DIRECTION.get(port.direction, "input"))
        decls[sig] = d
    r = _plain_range(port.name)
    if r is None:
        # A clock, and a cdc_control, are single-bit by nature: 8.1 calls the
        # control of a multi-bit crossing "a single-bit control port", and a
        # clock port has no width to declare. Only a data port whose width the
        # collateral does not state needs a parameter.
        if port.type in ("data",):
            d.width_param = True
    elif d.msb is None:
        d.msb, d.lsb = r
    else:
        d.msb = max(d.msb, r[0])
        d.lsb = min(d.lsb, r[1])
    return d


def _render_ports(decls: dict, order: list) -> tuple:
    """`(parameter block or '', port list text)`."""
    params, ports = [], []
    for sig in order:
        d = decls[sig]
        if d.width_param and d.msb is None:
            params.append(
                f"  // 4.3.1: \"If the name does not include a range, it applies to all\n"
                f"  // bits of the port.\" The collateral declares no resolvable range for\n"
                f"  // {d.signal}, so its width is a parameter — set it from the RTL.\n"
                f"  parameter {d.signal.upper()}_W = 1")
        ports.append(d.render())
    head = ""
    if params:
        head = "#(\n" + ",\n".join(params) + "\n)"
    return head, ",\n".join(ports)


# --------------------------------------------------------------------------
# Clause 8.4 — the verification clock
# --------------------------------------------------------------------------
def _relation(src, dst):
    """Clause 8.4's three crossing types, when both speeds are declared."""
    if src is None or dst is None:
        return None
    if src > dst:
        return "fast-to-slow"
    if src < dst:
        return "slow-to-fast"
    return "same-speed"


_ADVICE = {
    "fast-to-slow":
        "faster source into a slower destination is \"more problematic\" (8.4): "
        "sample on the source clock or on a faster virtual clock",
    "slow-to-fast":
        "the destination clock is the faster of the two, so it is already the "
        "better of them; a virtual clock would still see sub-period glitches",
    "same-speed":
        "same speed, possibly different phase: neither clock is faster, so only "
        "a faster virtual clock can see a glitch narrower than the period",
    None:
        "-frequency is not declared for both clocks, so 8.4's classification "
        "cannot be determined here",
}


def _fmt_hz(v):
    if v is None:
        return "not declared"
    for scale, unit in ((1e9, "GHz"), (1e6, "MHz"), (1e3, "kHz")):
        if v >= scale:
            return f"{v / scale:g} {unit}"
    return f"{v:g} Hz"


def _clause84(col: Collateral, all_sites: list) -> str:
    """The 8.4 note: every destination clock, and the speed of each crossing."""
    lines = [
        "// ---------------------------------------------------------------------------",
        "// Clause 8.4 — verification clock for each crossing.",
        "//",
        "// \"To verify the data stability, for dynamic verification, the most obvious",
        "// choice of clock is the destination domain clock. However, it may not be the",
        "// most prudent choice ... it is better to use either the fastest clock",
        "// available between the two clocks or create a verification-only virtual clock",
        "// that can be multiple orders of magnitude faster than the fastest of two",
        "// clocks participating in the crossing. Having this fastest clock will help",
        "// capture glitches in source data that are smaller than the sampling clock",
        "// frequency, which may occur when the crossing is enabled.\"",
        "//",
        "// Destination clocks in this file: "
        + (", ".join(sorted({s.clock for s in all_sites})) or "(none)"),
        "//",
    ]
    head = ("//   " + "crossing".ljust(22) + "source clock".ljust(24)
            + "destination clock".ljust(24) + "8.4 relation")
    lines.append(head)
    lines.append("//   " + "-" * 88)
    for s in all_sites:
        srcs = [c for c in s.port.associated_from_clocks
                if _clock_port(col, c) is not None]
        src_txt = ", ".join(srcs) if srcs else "(not declared)"
        src_hz = _hz(col.ports[srcs[0]].raw.get("frequency")) if srcs else None
        dst_hz = _hz(col.ports[s.clock].raw.get("frequency"))
        rel = _relation(src_hz, dst_hz)
        if len(srcs) > 1:
            rel = None
        cell_src = f"{src_txt} ({_fmt_hz(src_hz)})" if srcs else src_txt
        cell_dst = f"{s.clock} ({_fmt_hz(dst_hz)})"
        if s.virtual:
            cell_dst = f"{s.clock} (virtual)"
        lines.append("//   " + s.expr.ljust(22) + cell_src.ljust(24)
                     + cell_dst.ljust(24) + (rel or "not determined"))
    lines.append("//")
    seen = set()
    for s in all_sites:
        srcs = [c for c in s.port.associated_from_clocks
                if _clock_port(col, c) is not None]
        src_hz = _hz(col.ports[srcs[0]].raw.get("frequency")) if srcs else None
        dst_hz = _hz(col.ports[s.clock].raw.get("frequency"))
        rel = None if len(srcs) > 1 else _relation(src_hz, dst_hz)
        key = (s.expr, s.clock, rel)
        if key in seen:
            continue
        seen.add(key)
        lines.append(f"//   {s.expr} -> {s.clock}: {_ADVICE[rel]}.")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# the assertion blocks
# --------------------------------------------------------------------------
def _warn(msg: str) -> str:
    return f"  // CDC-WARNING: {msg}"


def _site_block(col: Collateral, s: Site, prop_clock: str,
                use_sampling_edge: bool = True) -> list:
    """The 8.2 and 8.3 blocks for one site."""
    lines = []
    port, expr = s.port, s.expr
    edge = _edge(port) if use_sampling_edge else "posedge"
    if use_sampling_edge and port.sampling_edge:
        how = f", sampled on the {port.sampling_edge} edge"
    elif use_sampling_edge:
        how = (", sampling edge not declared (posedge used, see the warning below)")
    else:
        how = (f", sampled on the verification clock {prop_clock} "
               f"(the destination is a virtual clock)")
    lines.append(f"  // {port.name} crosses into {s.clock}{how}")
    if use_sampling_edge and not port.sampling_edge:
        lines.append(_warn(
            f"Clause 8.2 defines no default for -sampling_edge and Table 3 makes it "
            f"conditional, so {port.name} -> {s.clock} is checked on posedge only "
            f"as a flagged assumption. If the first flop samples on the falling "
            f"edge, add -sampling_edge neg: the window below would then start on "
            f"the wrong edge."))
    for bad in s.unresolved_clocks:
        lines.append(_warn(
            f"-associated_to_clocks names {bad!r}, which is not a declared clock "
            f"(Table 3 requires every referenced name to be declared). No check "
            f"emitted for it rather than a check against something else."))

    lines.append(f"  property p_cdc_stable_{s.uid};")
    # Clause 8.2: "stable for four clock edges of the destination clock". Two
    # full periods is four edges; [*3] was six, so the assertion was stricter
    # than the standard while its own message claimed four.
    lines.append(f"    @({edge} {prop_clock}) $changed({expr}) |-> "
                 f"$stable({expr})[*2];")
    lines.append("  endproperty")
    if use_sampling_edge:
        lines.append(f"  // Clause 8.2: stable for four {s.clock} edges after a "
                     f"change (two periods).")
    else:
        lines.append(f"  // Clause 8.2: stable for four {s.clock} edges after a "
                     f"change (two periods), counted on {prop_clock}, the "
                     f"verification clock standing in for {s.clock} (8.4).")
    lines.append(f"  a_cdc_stable_{s.uid}: assert property (p_cdc_stable_{s.uid})")
    lines.append(f"    else $error(\"{port.name} changed inside the 4-edge window "
                 f"of {s.clock}\");")
    lines.append("")

    setup, hold = port.control_setup, port.control_hold
    resolved, unresolved = _control_ports(col, port)

    for bad in unresolved:
        declared = col.ports.get(bad)
        why = ("it is not declared in the collateral" if declared is None
               else f"it is declared as -type {declared.type!r}, not cdc_control")
        # Clause 8.3 needs the port that enables the crossing. Guessing one is
        # an assertion on an event the collateral never named.
        lines.append(_warn(
            f"-cdc_control names {bad!r} for {port.name} but {why}. No 8.3 "
            f"setup/hold check is emitted for it: the enable edge is unknown, and "
            f"substituting another port would assert on a different event."))
        lines.append("")

    if (setup or hold) and not resolved and not unresolved:
        lines.append(_warn(
            f"{port.name} declares -cdc_control_setup/-cdc_control_hold but no "
            f"-cdc_control. Table 3 puts the margins on the crossing's cdc_control "
            f"port; without one there is no enable event, so no 8.3 check is "
            f"emitted."))
        lines.append("")

    ctrl_seen = set()
    for ctrl in resolved:
        cu = _ident(ctrl.base_name)
        if cu in ctrl_seen:
            n = 2
            while f"{cu}_{n}" in ctrl_seen:
                n += 1
            cu = f"{cu}_{n}"
        ctrl_seen.add(cu)
        lines.extend(_control_block(col, s, ctrl, cu, prop_clock, edge, setup, hold))
    return lines


def _control_block(col, s: Site, ctrl: Port, cu: str, prop_clock: str,
                   edge: str, setup: str, hold: str) -> list:
    """Clause 8.3 for one (crossing, control) pair."""
    lines = []
    port, expr = s.port, s.expr
    setup, hold = _margins(port, ctrl) if not (setup or hold) else (setup, hold)
    setup_n, hold_n = _cycles(setup), _cycles(hold)

    pol = port_polarity(col, ctrl)
    if pol == "low":
        enable, disable = f"$fell({ctrl.name})", f"$rose({ctrl.name})"
    elif pol in ("high", ""):
        enable, disable = f"$rose({ctrl.name})", f"$fell({ctrl.name})"
        if pol == "":
            # Table 3: "-polarity ... is mandatory for async reset, cdc_control,
            # and rdc_control". An absent value is a non-conformant file, and the
            # enable edge is then an assumption, so it is flagged, not hidden.
            lines.append(_warn(
                f"{ctrl.name} is a cdc_control port with no -polarity; Table 3 "
                f"makes -polarity mandatory for cdc_control. The 8.3 check below "
                f"assumes active-high ($rose enables)."))
    else:
        lines.append(_warn(
            f"{ctrl.name} declares -polarity {pol!r}, which Table 3 does not allow "
            f"for cdc_control ('low_high' is not allowed). No 8.3 check emitted."))
        return lines

    for label, value, n in (("-cdc_control_setup", setup, setup_n),
                            ("-cdc_control_hold", hold, hold_n)):
        if value and n is None:
            lines.append(f"  // {label} = {value!r} is not an integer cycle count.")
            lines.append("  // Table 3 defines it as destination clock cycles; no "
                         f"{label.split('_')[-1]} check emitted.")
        elif value and n is not None and n < 0:
            lines.append(f"  // {label} = {n} is negative: Table 3 reads a negative "
                         f"margin as permission for the data to move on the other "
                         f"side of the control edge, which this emitter cannot "
                         f"express. No check emitted rather than a wrong one.")

    if setup_n:
        low = pol == "low"
        lines.append(f"  // Clause 8.3: -cdc_control_setup = {setup_n} destination "
                     f"clock cycle(s), control {ctrl.name} active "
                     f"{'low' if low else 'high'}.")
        lines.append(f"  property p_cdc_setup_{s.uid}_{cu};")
        # `$stable(x)[-N]` is not legal SVA — a repetition looks forward. The
        # window before the enable is expressed by comparing the signal with
        # its own past value at each cycle of the window.
        conjuncts = " && ".join(
            f"({expr} == $past({expr},{i}))" for i in range(1, setup_n + 1))
        lines.append(f"    @({edge} {prop_clock}) {enable} |-> ({conjuncts});")
        lines.append("  endproperty")
        lines.append(f"  a_cdc_setup_{s.uid}_{cu}: assert property "
                     f"(p_cdc_setup_{s.uid}_{cu})")
        lines.append(f"    else $error(\"{port.name} not stable {setup_n} cycle(s) "
                     f"before {ctrl.name} enabled the crossing\");")
        lines.append("")
    if hold_n:
        lines.append(f"  // Clause 8.3: -cdc_control_hold = {hold_n} destination "
                     f"clock cycle(s).")
        lines.append(f"  property p_cdc_hold_{s.uid}_{cu};")
        lines.append(f"    @({edge} {prop_clock}) {disable} |-> "
                     f"$stable({expr})[*{hold_n}];")
        lines.append("  endproperty")
        lines.append(f"  a_cdc_hold_{s.uid}_{cu}: assert property "
                     f"(p_cdc_hold_{s.uid}_{cu})")
        lines.append(f"    else $error(\"{port.name} not stable {hold_n} cycle(s) "
                     f"after {ctrl.name} disabled the crossing\");")
        lines.append("")
    return lines


def assertions_for(col: Collateral, port: Port) -> str:
    """The assertion block(s) for one crossing port — one per destination clock."""
    all_sites = sites(col)
    mine = [s for s in all_sites if s.port is port]
    if not mine:
        return ""
    out = []
    for s in mine:
        out.append("\n".join(_site_block(col, s, s.clock)))
    return "\n".join(out)


# --------------------------------------------------------------------------
# the module
# --------------------------------------------------------------------------
def _module(col: Collateral, name: str, block_sites: list, clk_map: dict) -> str:
    """One checker module over `block_sites`.

    `clk_map` maps a destination clock to the clock the property is actually
    sampled on. They differ only for a virtual clock, whose verification-clock
    stand-in is a real input of this module (and is not the virtual port).
    """
    decls, order = {}, []

    sigmap = _signals(col)

    def touch(p: Port):
        sig = sigmap[p.base_name]
        _add_decl(decls, p, sigmap)
        if sig not in order:
            order.append(sig)

    for propname in dict.fromkeys(clk_map.values()):
        real = col.ports.get(propname)
        if real is not None and real.type != "virtual_clock":
            touch(real)
        else:
            # The verification clock for a virtual clock: a real 1-bit input of
            # this module, deliberately not named after the virtual port.
            decls[propname] = Decl(signal=propname, direction="input")
            order.append(propname)
    for s in block_sites:
        touch(s.port)
    for s in block_sites:
        for ctrl in _control_ports(col, s.port)[0]:
            touch(ctrl)

    out = []
    head, ports = _render_ports(decls, order)
    out.append(f"module {name} {head}(" if head else f"module {name} (")
    out.append(ports)
    out.append(");")
    out.append("")
    for sig in order:
        d = decls[sig]
        if d.msb is not None and d.direction:
            out.append(
                f"  // {d.signal} is declared with the range the collateral names "
                f"([{d.msb}:{d.lsb}]). Widen this declaration if the RTL port is "
                f"wider, or the bind will not connect the whole port.")
            out.append("")
    for raw, sig in sigmap.items():
        if _ident(raw) == sig and re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", raw):
            continue
        out.append(_warn(
            f"the collateral names the port {raw!r}, which is not a plain "
            f"SystemVerilog identifier; it is declared here as {sig!r}. Connect "
            f"this port explicitly (an escaped identifier or a bind with named "
            f"port connections) rather than relying on a name match."))
        out.append("")
    for s in block_sites:
        out.append("\n".join(_site_block(col, s, clk_map[s.clock],
                                         use_sampling_edge=not s.virtual)))
    out.append("endmodule")
    return "\n".join(out)


def emit(col: Collateral, module: str | None = None) -> str:
    """Emit a complete SystemVerilog file of CDC assertions."""
    mod = module or col.module or "cdc_assertions"
    all_sites = sites(col)
    real = [s for s in all_sites if not s.virtual]
    virt = [s for s in all_sites if s.virtual]

    out = [HEADER.format(module=mod)]

    if not all_sites:
        out.append("// No data port declares an -associated_to_clocks destination, so "
                   "there")
        out.append("// is no crossing this collateral lets a closed box check.")
        out.append("")
        out.append(f"module {mod}_cdc_checks;")
        out.append("endmodule")
        return "\n".join(out) + "\n"

    out.append(_clause84(col, all_sites))
    out.append("")

    if virt:
        # Table 3: type virtual_clock "defines a virtual clock port that does not
        # match an actual port in the module". Declaring it as an input of the
        # bound checker gives a port no bind can drive, so it is not declared at
        # all; the crossings that use one are checked against an explicit
        # verification clock instead, which is what 8.4 recommends.
        names = sorted({s.clock for s in virt})
        out.append("// Clause 8.4 / Table 3 — virtual destination clock(s): "
                   + ", ".join(names))
        out.append("// A virtual clock \"does not match an actual port in the module\", so")
        out.append("// it is NOT declared as a port of "
                   f"{mod}_cdc_checks. The crossings that use one")
        out.append(f"// are checked in {mod}_cdc_checks_vclk instead, which takes one")
        out.append("// explicit verification-clock input per virtual clock. Connect it to a")
        out.append("// generated clock \"multiple orders of magnitude faster than the fastest")
        out.append("// of two clocks participating in the crossing\" (8.4), not to the")
        out.append("// virtual clock itself. That module cannot be bound by name.")
        out.append("")

    if real:
        out.append(_module(col, f"{mod}_cdc_checks", real,
                           {s.clock: s.clock for s in real}))
    else:
        out.append("// Every crossing in this collateral uses a virtual clock, so")
        out.append(f"// {mod}_cdc_checks would have nothing to check.")
        out.append(f"module {mod}_cdc_checks;")
        out.append("endmodule")

    if virt:
        clk_map, vports = {}, []
        for s in virt:
            if s.clock not in clk_map:
                nm = "clk_virtual" if not clk_map else f"clk_virtual_{len(clk_map) + 1}"
                clk_map[s.clock] = nm
                vports.append((s.clock, nm))
        out.append("")
        out.append("// One verification clock per virtual destination clock. These are NOT")
        out.append("// ports of the IP; connect them from the testbench or a bind with")
        out.append("// explicit port connections.")
        for orig, nm in vports:
            out.append(f"//   {nm}  <- verification clock for virtual clock {orig}")
        out.append("")
        out.append(_module(col, f"{mod}_cdc_checks_vclk", virt, clk_map))

    return "\n".join(out) + "\n"
