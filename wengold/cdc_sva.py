"""Clause 8 — SVA for closed-box CDC integrity, emitted from the collateral.

The standard's premise is that at SoC level the IP is a **closed box**: you have
its CDC collateral and its ports, and nothing else. So the only assertions you can
write are at the port boundary, and they are all about *stability*:

  8.2  a crossing signal must be stable for **four destination clock edges** for
       an N-flop synchroniser. `-sampling_edge` (`pos`/`neg`) says which edge of
       the first flop samples it.
  8.3  `-cdc_control_setup` is how long the data must be stable **before** its
       control enables the crossing; `-cdc_control_hold` how long **after** it
       disables.
  8.4  the destination clock may not be the right verification clock — a glitch
       narrower than the sampling clock is invisible to it. A faster clock is
       better, and the emitted header says so.

What this emits, and what it will not
-------------------------------------
It emits assertions that check the *declared* requirements are met by the
waveforms. It does **not** assert that a crossing is safe, because a closed box
cannot see the synchroniser: the standard is explicit that "closed box level CDC
verification cannot verify the integrity of crossings using a destination domain
control signal that enables the crossing due to its invisibility outside the closed
box". An assertion here that passed would mean "the data was stable as declared",
not "the design is correct".

`-cdc_control_setup` and `-cdc_control_hold` are **durations** (`2ns`), and SVA
repetition counts **cycles**. This module does not invent a clock period: it emits
a parameter per port with the duration in the comment and a conservative default,
so the integrator sets it from their own timing. Guessing would produce assertions
that pass for the wrong reason.
"""
from __future__ import annotations

import re

from .cdc_standard import Collateral, Port

__all__ = ["emit", "assertions_for"]

HEADER = """// CDC assertions for {module}, generated by WENGOLD from Accellera CDC/RDC
// Interface Standard v1.0, Clause 8 (closed-box CDC integrity).
//
// These check that the DATA STABILITY the collateral declares actually holds in
// the waveforms. They do not prove a crossing is safe: a closed box cannot see
// the synchroniser, and the standard says so in 8.1.
//
// Clause 8.4 — the verification clock matters. Sampling on {clk} will miss any
// glitch narrower than that clock's period. For formal or dynamic proof, sample
// on the faster of the two clocks, or on a verification-only virtual clock.
//
// Set the *_CYCLES parameters below from your clock period. The declared
// durations are in the comments; they are NOT guessed here, because a wrong
// repetition count produces an assertion that passes for the wrong reason.
"""


def _edge(port: Port) -> str:
    """Clause 8.2: which edge of the first flop samples the crossing."""
    return "negedge" if port.sampling_edge == "neg" else "posedge"


def _ident(name: str) -> str:
    """A legal SystemVerilog identifier from a port name."""
    return re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "p"


def _control_for(col: Collateral, port: Port):
    """The port that enables this crossing, if the collateral names one."""
    named = (port.raw.get("cdc_control") or "").strip()
    if named and named in col.ports:
        return col.ports[named]
    for cand in col.ports.values():
        if cand is not port and cand.type in ("data", "static") \
                and "cdc_control" in cand.raw:
            return cand
    return None


def _crossing_ports(col: Collateral) -> list:
    """Data ports that declare a destination clock — the crossings we can check."""
    out = []
    for p in col.ports.values():
        if p.type != "data" or p.ignore:
            continue
        if not p.associated_to_clocks:
            continue
        dest = p.associated_to_clocks[0]
        if dest in col.ports and col.ports[dest].type in ("clock", "virtual_clock"):
            out.append(p)
    return sorted(out, key=lambda p: p.name)


def assertions_for(col: Collateral, port: Port) -> str:
    """The assertion block for one crossing port."""
    dest = port.associated_to_clocks[0]
    edge = _edge(port)
    n = _ident(port.base_name)
    lines = []
    lines.append(f"  // {port.name} crosses into {dest}"
                 + (f", sampled on the {port.sampling_edge} edge"
                    if port.sampling_edge else ", sampling edge not declared (pos assumed)"))
    lines.append(f"  property p_cdc_stable_{n};")
    lines.append(f"    @({edge} {dest}) $changed({port.name}) |-> $stable({port.name})[*3];")
    lines.append("  endproperty")
    lines.append(f"  // Clause 8.2: stable for four {dest} edges after a change.")
    lines.append(f"  a_cdc_stable_{n}: assert property (p_cdc_stable_{n})")
    lines.append(f"    else $error(\"{port.name} changed inside the 4-edge window of {dest}\");")
    lines.append("")

    setup, hold = port.control_setup, port.control_hold
    ctrl = _control_for(col, port)
    if (setup or hold) and ctrl is not None:
        c = _ident(ctrl.base_name)
        if setup:
            lines.append(f"  // Clause 8.3: declared -cdc_control_setup = {setup}.")
            lines.append(f"  // Convert to cycles at your clock period and set "
                         f"SETUP_CYCLES_{n}.")
            lines.append(f"  parameter int SETUP_CYCLES_{n} = 1;")
            lines.append(f"  property p_cdc_setup_{n};")
            lines.append(f"    @({edge} {dest}) $rose({ctrl.name}) |-> "
                         f"$stable({port.name})[-SETUP_CYCLES_{n}];")
            lines.append("  endproperty")
            lines.append(f"  a_cdc_setup_{n}: assert property (p_cdc_setup_{n})")
            lines.append(f"    else $error(\"{port.name} not stable {setup} before "
                         f"{ctrl.name} enabled the crossing\");")
            lines.append("")
        if hold:
            lines.append(f"  // Clause 8.3: declared -cdc_control_hold = {hold}.")
            lines.append(f"  parameter int HOLD_CYCLES_{n} = 1;")
            lines.append(f"  property p_cdc_hold_{n};")
            lines.append(f"    @({edge} {dest}) $fell({ctrl.name}) |-> "
                         f"$stable({port.name})[*HOLD_CYCLES_{n}];")
            lines.append("  endproperty")
            lines.append(f"  a_cdc_hold_{n}: assert property (p_cdc_hold_{n})")
            lines.append(f"    else $error(\"{port.name} not stable {hold} after "
                         f"{ctrl.name} disabled the crossing\");")
            lines.append("")
    return "\n".join(lines)


def emit(col: Collateral, module: str | None = None) -> str:
    """Emit a complete SystemVerilog module of CDC assertions."""
    mod = module or col.module or "cdc_assertions"
    crossings = _crossing_ports(col)
    clock = crossings[0].associated_to_clocks[0] if crossings else "clk"

    out = [HEADER.format(module=mod, clk=clock)]
    if not crossings:
        out.append("// No data port declares an -associated_to_clocks destination, so there")
        out.append("// is no crossing this collateral lets a closed box check.")
        out.append(f"module {mod}_cdc_checks;")
        out.append("endmodule")
        return "\n".join(out) + "\n"

    declared = [c for p in crossings for c in p.associated_to_clocks]
    clocks = sorted({c for c in declared if c in col.ports})
    ports = list(crossings)
    # Every signal an assertion names must be a port of the generated module, or
    # the file does not compile. The control ports were named in the properties
    # but missing from the header.
    controls = []
    for p in crossings:
        c = _control_for(col, p)
        if c is not None and c.name not in {x.name for x in ports}:
            controls.append(c)
    signals = clocks + [p.name for p in ports] + [c.name for c in controls]
    out.append(f"module {mod}_cdc_checks (")
    out.append(",\n".join(f"  input logic {s}" for s in signals))
    out.append(");")
    out.append("")
    for p in ports:
        out.append(assertions_for(col, p))
    out.append("endmodule")
    return "\n".join(out) + "\n"
