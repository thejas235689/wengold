"""Clause 8 — SVA for closed-box CDC integrity, emitted from the collateral.

The standard's premise is that at SoC level the IP is a **closed box**: you have
its CDC collateral and its ports, and nothing else. So the only assertions you can
write are at the port boundary, and they are all about *stability*:

  8.2  "the crossing signal should be stable for four clock edges of the
       destination clock for an N-flop synchronizer". `-sampling_edge`
       (`pos`/`neg`) says which edge of the first flop samples it.
  8.3  `-cdc_control_setup` is how long the data must be stable **before** its
       control enables the crossing; `-cdc_control_hold` how long **after** it
       disables.
  8.4  the destination clock may not be the right verification clock — a glitch
       narrower than the sampling clock is invisible to it. A faster clock is
       better, and the emitted header says so.

What this emits, and what it will not
-------------------------------------
It emits assertions that check the *declared* requirements are met by the
waveforms. It does **not** assert that a crossing is safe, because a closed box
cannot see the synchroniser: the standard is explicit that "closed box level CDC
verification cannot verify the integrity of crossings using a destination domain
control signal that enables the crossing due to its invisibility outside the closed
box". An assertion here that passed would mean "the data was stable as declared",
not "the design is correct".

Legality and bindability are part of the claim. An assertion that cannot
elaborate, or a module that cannot be bound, protects nothing, so this emitter:

  * sanitises every port name into a legal SystemVerilog identifier and
    de-duplicates the property and assertion names that result (8.2, 8.3);
  * declares each signal with the direction the collateral declares and with
    the width the collateral declares in the port's range — 4.3.1: "If the name
    does not include a range, it applies to all bits of the port", so an
    un-ranged port gets a width *parameter* rather than a guessed number;
  * never declares a `-type virtual_clock` port as a module input: Table 3 says
    it "defines a virtual clock port that does not match an actual port in the
    module", so a bind-by-name has nothing to connect it to. Those crossings go
    into a second module with one explicit verification-clock input (8.4);
  * emits one 8.3 block per control named in `-cdc_control`, which Table 3 makes
    a "space-separated list {associated-ports}";
  * emits one 8.2 check per entry of `-associated_to_clocks` (also a
    "space-separated list {clock-names}"), not just the first;
  * refuses rather than guesses: a `-cdc_control` that does not resolve to a
    declared `cdc_control` port gets a comment, not an arbitrary data port used
    as an enable;
  * says so when `-sampling_edge` is absent, because the standard defines no
    default — 8.2 only says "The port domain attribute -sampling_edge is used to
    define the active sampling edge of the first flop of a synchronizer".

`-cdc_control_setup` and `-cdc_control_hold` are **counts of destination clock
cycles** (Table 3: "the number of destination clock cycles the
associated_inputs data port shall be stable before the cdc_control port enables
the data crossing"), so they are used directly. This module does not invent a
clock period: a guessed repetition count would produce assertions that pass for
the wrong reason.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .cdc_standard import Collateral, Port

__all__ = ["emit", "assertions_for", "sites", "Site"]

# Table 3, attribute `logic`: "Without this attribute, the assumption is that the
# port directly reaches a sequential element." These words can appear inside an
# -associated_to_clocks list because Annex A writes a destination as
# {clk0_i internal_sync} — clock and logic in one braced item, which this
# parser's whitespace split flattens. They are not clocks.
LOGIC_WORDS = {"combo", "inverter", "glitch_free_combo", "internal_sync"}

# Table 3: direction is a "defined set {input, output, inout}"; the parser also
# accepts the short forms.
DIRECTION = {"in": "input", "input": "input", "out": "output",
             "output": "output", "inout": "inout"}

HEADER = """// CDC assertions for {module}, generated by WENGOLD from Accellera CDC/RDC
// Interface Standard v1.0, Clause 8 (closed-box CDC integrity).
//
// These check that the DATA STABILITY the collateral declares actually holds in
// the waveforms. They do not prove a crossing is safe: a closed box cannot see
// the synchroniser, and 8.1 says so — "Closed box level CDC verification cannot
// verify the integrity of crossings using a destination domain control signal
// that enables the crossing due to its invisibility outside the closed box."
//
// Declared counts and declared widths are used as declared; they are NOT guessed here.
// Clause 8.3 margins are integer counts of destination clock cycles (Table 3),
// and a width the collateral does not declare becomes a parameter you set from
// the RTL, because a wrong repetition count or a wrong width produces an
// assertion that passes for the wrong reason.
"""


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------
def _ident(name: str) -> str:
    """A legal SystemVerilog identifier from a port name.

    A port name may carry characters an identifier cannot: `DATA[7:4]`, `a.b`,
    `8bit`. Each of those used verbatim produced a property name (and, for a
    duplicate, a *second* property name identical to the first) that no tool
    could elaborate.
    """
    s = re.sub(r"[^A-Za-z0-9_$]", "_", (name or "").strip())
    s = re.sub(r"_+", "_", s).strip("_")
    if not s:
        return "p"
    if s[0].isdigit():
        s = "_" + s          # an identifier may not begin with a digit
    return s


def _select(name: str) -> str:
    """The `[..]` tail of a port name, or '' when the name has no range."""
    s = (name or "").strip()
    i = s.find("[")
    return s[i:] if i >= 0 else ""


def _plain_range(name: str):
    """`(msb, lsb)` when the port's range is a plain integer range, else None.

    4.3.1: "If the name does not include a range, it applies to all bits of the
    port." A range like `[MSB:LSB]` is a parameter expression this emitter does
    not resolve.
    """
    sel = _select(name)
    m = re.fullmatch(r"\[\s*(-?\d+)\s*(?::\s*(-?\d+)\s*)?\]", sel)
    if not m:
        return None
    msb = int(m.group(1))
    lsb = int(m.group(2)) if m.group(2) is not None else msb
    return (msb, lsb) if msb >= lsb else (lsb, msb)


def _cycles(value):
    """The declared setup/hold as a cycle count, or None if it is not one.

    Table 3 makes these an integer count of destination clock cycles, so `3` is
    three cycles. A value like `2ns` is **not** the standard's form, and this
    returns None for it so the caller can say so — dropping the check silently
    would be the same failure as the bug this replaced.
    """
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def port_polarity(col: Collateral, port) -> str:
    """`-polarity` of a control port, lowercased. Empty when undeclared."""
    return (getattr(port, "raw", {}).get("polarity") or "").strip().lower()


def _edge(port: Port) -> str:
    """Clause 8.2: which edge of the first flop samples the crossing.

    The standard defines no default — Table 3 makes `-sampling_edge` conditional
    and 8.2 only says what the attribute *is for* — so an absent value is
    reported by the caller rather than being treated as declared.
    """
    return "negedge" if port.sampling_edge == "neg" else "posedge"


def _hz(value):
    """A declared `-frequency` in Hz, or None when it is not a number we know."""
    s = re.sub(r"\s+", "", str(value or ""))
    m = re.fullmatch(r"([0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?)([kKmMgG]?)(?:[hH][zZ])?", s)
    if not m:
        return None
    scale = {"": 1.0, "k": 1e3, "m": 1e6, "g": 1e9}[m.group(2).lower()]
    return float(m.group(1)) * scale


def _decl(col: Collateral, name: str) -> Port | None:
    """The declared port `name`, if it exists."""
    return col.ports.get(name)


def _clock_port(col: Collateral, name: str) -> Port | None:
    p = col.ports.get(name)
    if p is not None and p.type in ("clock", "virtual_clock"):
        return p
    return None


