@dataclass
class Site:
    """One check site: a data port crossing into one destination clock."""

    port: Port
    clock: str                 # destination clock, as the collateral names it
    virtual: bool = False      # Table 3: virtual_clock "does not match an
                               # actual port in the module"
    uid: str = ""
    sig: str = ""              # the identifier this site reads (see _signals)
    unresolved_clocks: list = field(default_factory=list)

    @property
    def expr(self) -> str:
        """The expression the assertion names.

        A declared slice (`DATA[7:4]`) is a legal part-select of the declared
        signal; a parameterised slice (`DATA[MSB:LSB]`) is not resolvable here,
        so the whole declared signal is used and the comment says so.
        """
        r = _plain_range(self.port.name)
        if r is None:
            return self.sig
        return f"{self.sig}[{r[0]}:{r[1]}]"


def _signals(col: Collateral) -> dict:
    """Map each declared port's base name to the identifier used for it.

    Two distinct declared names can sanitise to the same identifier (`a.b` and
    `a-b` both become `a_b`). Merging them would make two checks read one
    signal — an assertion about a signal the collateral never named — so the
    second gets its own identifier and the module says so.
    """
    out, used = {}, {}
    for name in sorted(col.ports):
        raw = col.ports[name].base_name
        if raw in out:
            continue
        sig = _ident(raw)
        if sig in used and used[sig] != raw:
            n = 2
            while f"{sig}_{n}" in used:
                n += 1
            sig = f"{sig}_{n}"
        out[raw] = sig
        used[sig] = raw
    return out


def sites(col: Collateral) -> list:
    """Every (data port, destination clock) pair the collateral lets us check.

    Clause 8 / Table 3: `-associated_to_clocks` is a "space-separated list
    {clock-names}", and Annex A shows one port fanned out to several receivers
    (`{clk1_i {clk0_i internal_sync} clk0_i}`). Each entry is its own crossing,
    so each gets its own check.
    """
    out = []
    sigmap = _signals(col)
    for p in sorted(col.ports.values(), key=lambda x: x.name):
        if p.type != "data" or p.ignore:
            continue
        if not p.associated_to_clocks:
            continue
        seen, bad = [], []
        for entry in p.associated_to_clocks:
            if entry in LOGIC_WORDS:
                continue
            if entry in seen or entry in bad:
                continue
            if _clock_port(col, entry) is None:
                # Referential consistency is check()'s finding, not silently
                # turned into a check against something else.
                bad.append(entry)
                continue
            seen.append(entry)
            out.append(Site(port=p, clock=entry,
                            virtual=_clock_port(col, entry).type == "virtual_clock",
                            sig=sigmap[p.base_name], unresolved_clocks=[]))
        for s in out:
            if s.port is p:
                s.unresolved_clocks = list(bad)
    _assign_uids(out)
    return out


def _base_uid(s: Site) -> str:
    """The identifier stem for a site: the port's whole declared name, sanitised.

    `DATA[7:4]` and `DATA[3:0]` share a `base_name` (`DATA`) but are different
    crossings, so the stem comes from the full name: `DATA_7_4` and `DATA_3_0`.
    """
    return _ident(s.port.name)


def _assign_uids(all_sites: list) -> None:
    """Give every site a unique identifier stem.

    Two ports that share a `base_name` (the slices `DATA[7:4]` and `DATA[3:0]`,
    or `a.b` and `a-b`) would otherwise emit the *same* property and assertion
    names twice, which is a redefinition: the file does not elaborate.
    """
    counts = {}
    for s in all_sites:
        counts[_base_uid(s)] = counts.get(_base_uid(s), 0) + 1
    used = set()
    for s in all_sites:
        stem = _base_uid(s)
        cand = stem if counts[stem] == 1 else f"{stem}_{_ident(s.clock)}"
        uid, i = cand, 2
        while uid in used:
            uid = f"{cand}_{i}"
            i += 1
        used.add(uid)
        s.uid = uid


def _control_ports(col: Collateral, port: Port):
    """`(resolved, unresolved)` for the port's `-cdc_control` list.

    Table 3: `cdc_control` is a "space-separated list {associated-ports}" and is
    "mandatory for a data port if it is paired with a port of type cdc_control".
    A name that does not resolve is returned as unresolved: picking another port
    as the enable would assert on an event the collateral never named.
    """
    names = [n for n in (port.raw.get("cdc_control") or "").split() if n]
    resolved, unresolved = [], []
    for n in names:
        p = col.ports.get(n)
        if p is not None and p.type == "cdc_control":
            resolved.append(p)
        else:
            unresolved.append(n)
    return resolved, unresolved


def _margins(port: Port, ctrl: Port):
    """`(setup, hold)` for this crossing.

    Table 3 puts both on the port with the `cdc_control` attribute ("Sets a
    constant value on a port with the cdc_control attribute ..."), and Annex A
    Example 50 does the same. Older collateral writes them on the data port, so
    both spellings are read; the data port wins when it declares them.
    """
    setup = port.control_setup or ctrl.control_setup
    hold = port.control_hold or ctrl.control_hold
    return setup, hold


