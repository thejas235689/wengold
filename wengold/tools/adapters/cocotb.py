"""cocotb adapter — Python testbenches against any simulator, fully open.

`run()` is a complete flow: it builds the environment, compiles and executes the
testbench through the project's Makefile, parses the JUnit `results.xml` cocotb
writes, collects the waveforms and logs, and returns an explicit Outcome. It
never reports a pass it cannot back with parsed results.
"""
from __future__ import annotations

import os
import shutil
from pathlib import Path

from ..base import ToolSpec
from ..outcome import (Outcome, ToolOutcome, outcome_from_cocotb,
                       parse_cocotb_results, run_tool)
from ..registry import TOOL_GROUPS

SPEC: ToolSpec = next(t for t in TOOL_GROUPS["simulation"] if t.key == "cocotb")

_MAKEFILE = """\
# cocotb runner generated by WENGOLD
SIM ?= verilator
TOPLEVEL_LANG ?= verilog
VERILOG_SOURCES ?= {sources}
TOPLEVEL ?= {toplevel}
MODULE ?= {module}
EXTRA_ARGS += --trace --trace-structs
include $(shell cocotb-config --makefiles)/Makefile.sim
"""

_SYNTHETIC_RESULTS = """\
<?xml version="1.0" encoding="UTF-8"?>
<testsuite name="cocotb" tests="{tests}" failures="{failures}" errors="0" skipped="0">
  <testcase classname="{module}" name="smoke"/>
</testsuite>
"""


class CocotbAdapter:
    spec = SPEC

    def available(self) -> bool:
        if shutil.which("make") is None:
            return False
        try:
            import cocotb  # noqa: F401
            has_cocotb = True
        except Exception:
            has_cocotb = False
        has_sim = any(shutil.which(s) for s in ("verilator", "iverilog"))
        return has_cocotb or has_sim

    def write_makefile(self, workdir: str, toplevel: str, module: str | None = None,
                       sources: list[str] | None = None, overwrite: bool = False) -> str:
        path = Path(workdir) / "Makefile"
        if path.exists() and not overwrite:
            return str(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_MAKEFILE.format(
            sources=" ".join(sources or []),
            toplevel=toplevel,
            module=module or toplevel,
        ))
        return str(path)

    def run(self, *, workdir: str, toplevel: str, module: str | None = None,
            sim: str = "verilator", makefile: str = "Makefile", timeout: float = 900.0,
            seed: int | None = None, env: dict | None = None, dry_run: bool = False,
            results: str = "results.xml", tests: int = 1, failures: int = 0,
            collect: tuple[str, ...] = ("*.vcd", "*.fst", "results.xml", "*.log"),
            extra_make_args: tuple[str, ...] = ()) -> Outcome:
        """Compile and run a cocotb testbench, returning an explicit Outcome.

        `dry_run` writes a synthetic results.xml and returns a deterministic
        outcome — used by the demo and tests when no simulator is installed.
        """
        wd = Path(workdir)
        wd.mkdir(parents=True, exist_ok=True)

        if dry_run:
            (wd / results).write_text(_SYNTHETIC_RESULTS.format(
                tests=tests, failures=failures, module=module or toplevel))
            counts = parse_cocotb_results(wd / results)
            outcome = outcome_from_cocotb(counts, ToolOutcome.INCONCLUSIVE)
            return Outcome("cocotb", "run", outcome, rc=0,
                           log=f"[dry-run] {counts}", duration=0.0,
                           artifacts=[str(wd / results)],
                           spec={"counts": counts, "dry_run": True, "sim": sim})

        if shutil.which("make") is None:
            return Outcome("cocotb", "run", ToolOutcome.TOOL_MISSING,
                           spec={"binary": "make"})

        env2 = dict(os.environ)
        env2.update({"SIM": sim, "TOPLEVEL": toplevel, "MODULE": module or toplevel})
        if seed is not None:
            env2["SEED"] = str(seed)
        if env:
            env2.update({k: str(v) for k, v in env.items()})

        base = run_tool("make", ["-f", makefile, *extra_make_args], tool="cocotb",
                        action="run", timeout=timeout, cwd=str(wd), env=env2,
                        collect=list(collect))

        counts = parse_cocotb_results(wd / results)
        if counts:
            base.spec["counts"] = counts
            base.outcome = outcome_from_cocotb(counts, base.outcome)
        elif base.outcome is ToolOutcome.PASS:
            # exited 0 but produced no parsed results — not a proven pass
            base.outcome = ToolOutcome.INCONCLUSIVE
            base.spec.setdefault("note", "no results.xml parsed")
        return base
