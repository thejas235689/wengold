"""Emit SystemVerilog from a validated ModuleSpec.

Two files come out of every run:

* ``<module>.sv`` — the RTL. It deliberately stays inside the subset the formal
  front-end can parse (`assign`, ternary, one posedge-clocked `always_ff` with
  non-blocking assignments), so a generated block can be *proven*, not only
  compiled.
* ``<module>_props.sv`` — the assertions the spec implies, kept apart from the
  synthesizable code so neither pollutes the other.

Emission is deterministic: the same spec always yields byte-identical RTL, which
is what makes the generated file usable as reproducible evidence.
"""
from __future__ import annotations

from .spec import Field, ModuleSpec, Register

_HEADER = """\
// -----------------------------------------------------------------------------
// Generated by WENGOLD {version} from {source}
// Module: {name}{desc}
//
// Do not edit by hand: change the spec and regenerate, so the code and the spec
// cannot drift apart.
//
// Emitted to the WENGOLD formal subset -- `assign`, ternary, and a single
// posedge-clocked always_ff with non-blocking assignments -- so this block can
// be proven as well as compiled.
// -----------------------------------------------------------------------------
"""


def _lit(value: int, width: int) -> str:
    digits = (width + 3) // 4
    return f"{width}'h{value & ((1 << width) - 1):0{digits}x}"


def _ports(spec: ModuleSpec) -> str:
    lines = []
    for p in spec.all_ports:
        lines.append(f"    {p.decl}")
    return ",\n".join(lines)


def _parameters(spec: ModuleSpec) -> str:
    if not spec.parameters:
        return ""
    items = []
    for p in spec.parameters:
        note = f"   // {p.desc}" if p.desc else ""
        items.append(f"    parameter int unsigned {p.name} = {p.value}{note}")
    return "#(\n" + ",\n".join(items) + "\n) "


def _addresses(spec: ModuleSpec) -> str:
    width = max((r.width for r in spec.registers), default=32)
    out = ["    // ---- register addresses ----"]
    for r in spec.registers:
        note = f"   // {r.desc}" if r.desc else ""
        out.append(f"    localparam logic [{width - 1}:0] {r.name}_ADDR = "
                   f"{_lit(r.addr, width)};{note}")
    return "\n".join(out)


def _state(spec: ModuleSpec) -> str:
    width = max((r.width for r in spec.registers), default=32)
    out = ["    // ---- register state ----"]
    for r in spec.registers:
        out.append(f"    logic [{width - 1}:0] {r.signal};")
    return "\n".join(out)


def _field_views(spec: ModuleSpec) -> str:
    """A named wire per field, sliced at the field's spec bit range.

    The slice is the contract: a spec may refer to a field by name, and the
    conformance check confirms each field appears at exactly the range the spec
    declares.
    """
    out = ["    // ---- field views, one per field at its spec bit range ----"]
    for r in spec.registers:
        for f in r.fields:
            sig = spec.field_signal(r, f)
            rng = "" if f.width == 1 else f"[{f.width - 1}:0] "
            # one line, not two: `wire x = y;` is a net declaration with a
            # continuous assignment. The name survives, which is what the
            # conformance check points at — only the redundant `assign` goes.
            out.append(f"    wire {rng}{sig} = {r.signal}[{f.bits}];"
                       f"   // {r.name}.{f.name} ({f.access})")
    return "\n".join(out)


def _write_logic(spec: ModuleSpec) -> list[str]:
    """The software-write branch of the clocked block, per register."""
    out = []
    for r in spec.registers:
        writable = [f for f in r.fields if f.sw_writable]
        if not writable:
            continue
        kw = "if" if not out else "end else if"
        cond = f"(reg_wr_i && (reg_addr_i == {r.name}_ADDR))"
        out.append(f"            {kw} {cond} begin")
        for f in writable:
            bits = f"[{f.bits}]"
            note = f"   // {f.name} ({f.access})"
            if f.access == "w1c":
                out.append(f"                {r.signal}{bits} <= "
                           f"{r.signal}{bits} & ~reg_wdata_i{bits};{note}")
            else:
                out.append(f"                {r.signal}{bits} <= "
                           f"reg_wdata_i{bits};{note}")
    if out:
        out.append("            end")
    return out


def _clocked(spec: ModuleSpec) -> str:
    width = max((r.width for r in spec.registers), default=32)
    out = ["    // ---- reset and software writes ----",
           f"    always_ff @(posedge {spec.clock}) begin",
           f"        if (!{spec.reset}) begin"]
    for r in spec.registers:
        out.append(f"            {r.signal} <= {_lit(r.reset_value, width)};"
                   f"   // {r.name}")
    out.append("        end else begin")
    body = _write_logic(spec)
    out.extend(body if body else ["            // no software-writable field"])
    out.append("        end")
    out.append("    end")
    return "\n".join(out)


def _readable_mask(r: Register) -> int | None:
    """A mask of readable bits, or None when the whole register is readable."""
    hidden = 0
    for f in r.fields:
        if not f.sw_readable:
            for b in range(f.lo, f.hi + 1):
                hidden |= 1 << b
    if not hidden:
        return None
    return ((1 << r.width) - 1) & ~hidden


def _read_path(spec: ModuleSpec) -> str:
    width = max((r.width for r in spec.registers), default=32)
    out = ["    // ---- read path ----", "    assign reg_rdata_o ="]
    for r in spec.registers:
        mask = _readable_mask(r)
        value = r.signal if mask is None else f"({r.signal} & {_lit(mask, width)})"
        out.append(f"        (reg_addr_i == {r.name}_ADDR) ? {value} :")
    out.append(f"        {_lit(0, width)};")
    return "\n".join(out)


def _behaviour(spec: ModuleSpec) -> str:
    if not spec.assigns:
        return ""
    out = ["", "    // ---- combinational behaviour ----"]
    for a in spec.assigns:
        out.append(f"    assign {a.target} = {a.expr};")
    return "\n".join(out)


def _version() -> str:
    """The version that produced the file — read, never hardcoded.

    The header is part of the artifact, so a stale constant in it makes the
    generated file misreport which generator produced it.
    """
    try:
        from .. import __version__
        return __version__
    except Exception:                      # pragma: no cover
        return "unknown"


def emit_rtl(spec: ModuleSpec, version: str | None = None) -> str:
    """The synthesizable SystemVerilog for this spec."""
    version = version or _version()
    parts = [_HEADER.format(version=version, source=spec.source or "<spec>",
                            name=spec.name,
                            desc=f" -- {spec.desc}" if spec.desc else "")]
    parts.append(f"module {spec.name} {_parameters(spec)}(\n{_ports(spec)}\n);")
    parts.append("")
    if spec.has_registers:
        parts.append(_addresses(spec))
        parts.append("")
        parts.append(_state(spec))
        parts.append("")
        parts.append(_field_views(spec))
        parts.append("")
        parts.append(_clocked(spec))
        parts.append("")
        parts.append(_read_path(spec))
    parts.append(_behaviour(spec))
    parts.append("")
    parts.append("endmodule")
    return "\n".join(parts) + "\n"


def _field_property(spec: ModuleSpec, reg: Register, fld: Field) -> list[str]:
    """The assertions a field's access mode implies."""
    sig = reg.signal
    bits = f"[{fld.bits}]"
    out = []
    if fld.access in ("ro", "r"):
        out.append(
            f"    // {reg.name}.{fld.name} is read-only: nothing in this module\n"
            f"    // writes it, so it must hold its reset value forever.\n"
            f"    ap_{reg.name.lower()}_{fld.name.lower()}_ro:\n"
            f"        assert property (@(posedge {spec.clock}) disable iff "
            f"(!{spec.reset}) {sig}{bits} == {_lit(fld.reset, fld.width)});")
    else:
        out.append(
            f"    // {reg.name}.{fld.name} ({fld.access}) may change only while a\n"
            f"    // write to this register is in progress.\n"
            f"    ap_{reg.name.lower()}_{fld.name.lower()}_stable:\n"
            f"        assert property (@(posedge {spec.clock}) disable iff "
            f"(!{spec.reset})\n"
            f"            (!(reg_wr_i && (reg_addr_i == {reg.name}_ADDR)) && "
            f"$past({spec.reset}))\n"
            f"                |-> {sig}{bits} == $past({sig}{bits}));")
    return out


def emit_props(spec: ModuleSpec, version: str | None = None) -> str:
    """The assertions the spec implies, as a separate SystemVerilog file."""
    if not spec.has_registers:
        return ""
    version = version or _version()
    lines = [_HEADER.format(version=version, source=spec.source or "<spec>",
                            name=f"{spec.name}_props",
                            desc=" -- properties implied by the spec"),
             # NOT `import {name}::*` — {name} is a module, not a package, and an
             # import of a module name is invalid SV. It also collided with the
             # module node in the graph and silently dropped the block.
             f"module {spec.name}_props (\n"
             f"{_ports(spec)}\n);",
             "",
             f"    // bound to {spec.name} by name; see the conformance report.",
             ""]
    for r in spec.registers:
        for f in r.fields:
            lines.extend(_field_property(spec, r, f))
            lines.append("")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def emit_map(spec: ModuleSpec) -> dict:
    """The address map the RTL is expected to implement, for the checker."""
    return {
        "module": spec.name,
        "registers": [
            {"name": r.name, "addr": r.addr, "width": r.width,
             "reset": r.reset_value,
             "fields": [{"name": f.name, "hi": f.hi, "lo": f.lo,
                         "access": f.access, "reset": f.reset}
                        for f in r.fields]}
            for r in spec.registers
        ],
        "ports": [{"name": p.name, "dir": p.direction, "width": p.width}
                  for p in spec.all_ports],
        "parameters": [{"name": p.name, "value": p.value} for p in spec.parameters],
    }
