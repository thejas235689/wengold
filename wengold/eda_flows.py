"""Opt-in EDA verification manifests for external, licensed and open tools.

No shell, command string, implicit tool pass or automatic signoff. The user
supplies a reviewed JSON recipe in their project, with an executable argument
vector and evidence targets. WENGOLD enforces a timeout and returns tool logs,
binary identity, input digests and artifact hashes. This is an integration
contract, not a replacement for an EDA methodology, foundry PDK or signoff.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import time

FLOWS = {
    "uvm": "SystemVerilog UVM simulator regression",
    "rustdv_sim": "RustDV simulator-backed regression",
    "pss": "Portable Stimulus generation/verification",
    "dft": "DFT or ATPG execution",
    "sta": "Static timing analysis with real constraints and libraries",
    "power": "Library and activity-based dynamic/leakage power analysis",
    "upf": "Power-aware RTL/UPF simulation",
    "physical_drc": "Foundry DRC",
    "physical_lvs": "Foundry LVS",
    "physical_pex": "Parasitic extraction",
    "physical_place_route": "Physical place and route implementation",
    "analog": "SPICE / AMS simulation",
    "layout": "Layout verification",
}
MAX_LOG = 16000


def _inside(root: Path, name: str, *, require_file=True) -> Path:
    if not isinstance(name, str) or not name or Path(name).is_absolute():
        raise ValueError("paths must be nonempty project-relative names")
    path = (root / name).resolve()
    if not path.is_relative_to(root):
        raise ValueError("path escapes project directory")
    if require_file and not path.is_file():
        raise ValueError("project input file missing: " + name)
    return path


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load(root, manifest_rel):
    root = Path(root).resolve()
    path = _inside(root, manifest_rel)
    if path.stat().st_size > 64_000:
        raise ValueError("manifest too large")
    data = json.loads(path.read_text())
    if not isinstance(data, dict) or data.get("kind") not in FLOWS:
        raise ValueError("unknown or missing EDA flow kind")
    argv = data.get("argv")
    if not isinstance(argv, list) or not 1 <= len(argv) <= 40 or any(
        not isinstance(x, str) or not x or len(x) > 2048 for x in argv
    ):
        raise ValueError("argv must be a bounded list of nonempty strings")
    # Prevent untrusted command names from resolving to an executable hidden
    # inside the project. Explicit path to a reviewed binary is also supported.
    executable = argv[0]
    if "/" in executable or "\\" in executable:
        candidate = Path(executable)
        if not candidate.is_absolute() or not candidate.is_file():
            raise ValueError("tool executable must be on PATH or an absolute file path")
        binary = str(candidate.resolve())
    else:
        binary = shutil.which(executable)
        if not binary:
            raise RuntimeError("EDA executable not installed: " + executable)
    declared_inputs = data.get("inputs")
    if not isinstance(declared_inputs, list) or not declared_inputs:
        raise ValueError("declare at least one input file for provenance")
    if len(declared_inputs) > 200:
        raise ValueError("too many input files")
    inputs = {name: _digest(_inside(root, name)) for name in declared_inputs}
    expected = data.get("artifacts", [])
    if not isinstance(expected, list) or len(expected) > 100:
        raise ValueError("artifacts must be a list with at most 100 entries")
    outputs = {name: _inside(root, name, require_file=False) for name in expected}
    timeout = data.get("timeout_seconds", 120)
    if isinstance(timeout, bool) or not isinstance(timeout, int) or not 1 <= timeout <= 900:
        raise ValueError("timeout_seconds must be 1..900")
    # A manifest is intentionally a reviewed executable configuration.
    # It must be explicitly selected by an engineer in the UI.
    return root, data, binary, argv, inputs, outputs, timeout, _digest(path)


def execute_manifest(project_root: str | Path, manifest_rel: str) -> dict:
    root, spec, binary, argv, inputs, outputs, timeout, manifest_hash = _load(
        project_root, manifest_rel)
    before_outputs = {
        name: (path.stat().st_mtime_ns, _digest(path)) if path.is_file() else None
        for name, path in outputs.items()
    }
    started = time.time()
    base = {"kind": spec["kind"], "scope": FLOWS[spec["kind"]],
            "manifest": manifest_rel, "manifest_sha256": manifest_hash,
            "executable": binary, "argv": argv,
            "inputs_sha256": inputs, "started_at": started}
    try:
        # These manifests are trusted executable instructions chosen by the
        # project engineer, not commands generated by the LLM.
        result = subprocess.run(
            [binary, *argv[1:]], cwd=root, shell=False, check=False,
            capture_output=True, text=True, timeout=timeout)
        log = (result.stdout + "\n" + result.stderr)[-MAX_LOG:]
        ok = result.returncode == 0
        status = "tool_completed" if ok else "tool_failed"
        code = result.returncode
    except subprocess.TimeoutExpired:
        log, status, code, ok = "EDA tool timeout", "tool_timeout", None, False
    except OSError as exc:
        log, status, code, ok = str(exc), "tool_unavailable", None, False
    seen = {name: _digest(path) for name, path in outputs.items() if path.is_file()}
    missing = [name for name in outputs if name not in seen]
    stale = [name for name, path in outputs.items()
             if name in seen and before_outputs[name] is not None and
             (path.stat().st_mtime_ns, seen[name]) == before_outputs[name]]
    if missing:
        ok = False
        status = "evidence_missing"
    elif stale:
        ok = False
        status = "stale_evidence"
    now_inputs = {}
    for name in inputs:
        try:
            now_inputs[name] = _digest(_inside(root, name))
        except (OSError, ValueError):
            now_inputs[name] = None
    if now_inputs != inputs:
        ok = False
        status = "input_changed_during_run"
    return {**base, "ok": ok, "status": status, "exit_code": code,
            "finished_at": time.time(), "log": log,
            "artifacts_sha256": seen, "missing_artifacts": missing,
            "stale_artifacts": stale,
            "input_unchanged": now_inputs == inputs,
            "qualification": "ENGINEERING TOOL RUN ONLY — not signoff"}


def inspect_manifest(project_root: str | Path, manifest_rel: str) -> dict:
    root, spec, binary, argv, inputs, outputs, timeout, hash_value = _load(
        project_root, manifest_rel)
    return {"kind": spec["kind"], "executable": binary, "argv": argv,
            "inputs_sha256": inputs, "artifacts_expected": list(outputs),
            "timeout_seconds": timeout, "manifest_sha256": hash_value,
            "warning": "Running a reviewed EDA manifest executes its configured tool; do not run untrusted manifests."}
