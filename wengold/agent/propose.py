"""Edit proposals the kernel can justify.

An "AI pane that proposes RTL edits" is only worth having if the proposals are
true. This module generates them from facts the kernel already proved, never from
a model's guess:

| proposal | the kernel fact behind it |
| --- | --- |
| stub the unresolved modules | `completeness()` names each module instantiated but not defined |
| exclude a duplicate definition | two files declare the same module and the graph keeps one |
| isolate a singular block | `conditioning()` shows one block voids a large share of the evidence |

Every proposal is a **unified diff** against a real path, and nothing is applied
here — `Proposal.apply()` is a separate, explicit call. A tool that edits RTL
without showing the diff first is not one you would let near silicon signoff.

**What this deliberately does not do.** It does not write RTL logic, guess a
missing module's behaviour, or invent a fix for a failing check. Stubs are empty
by construction and say so. If you want free-form generation, that is a model's
job and it belongs behind the same diff gate — `Proposal` is the gate.
"""
from __future__ import annotations

import difflib
from dataclasses import dataclass, field
from pathlib import Path

__all__ = ["Proposal", "propose_stubs", "propose_duplicate_exclusion",
           "propose_all", "STUB_FILE"]


STUB_FILE = "wengold_stubs.sv"


@dataclass
class Proposal:
    """One edit, as a diff, with the fact that justifies it."""

    id: str
    title: str
    rationale: str            # the kernel fact, quoted
    path: str                 # file the diff applies to
    diff: str                 # unified diff, ready to display
    new_text: str = ""        # full new content (empty = create nothing)
    kind: str = "create"      # "create" | "append"
    facts: dict = field(default_factory=dict)

    def render(self) -> str:
        return (f"  {self.title}\n"
                f"    why: {self.rationale}\n"
                f"    file: {self.path}\n"
                + "\n".join("      " + ln for ln in self.diff.splitlines()[:24]))

    def apply(self, root: str | Path) -> Path:
        """Write the proposal. Caller must have shown the diff first."""
        p = Path(root) / self.path
        p.parent.mkdir(parents=True, exist_ok=True)
        if self.kind == "create" or not p.exists():
            p.write_text(self.new_text)
        else:
            p.write_text(p.read_text() + self.new_text)
        return p


def _diff(path: str, before: str, after: str) -> str:
    return "".join(difflib.unified_diff(
        before.splitlines(keepends=True), after.splitlines(keepends=True),
        fromfile=f"a/{path}", tofile=f"b/{path}"))


def _port_names(graph, node: str) -> list[str]:
    """Best-effort port list for a stub. An empty port list is honest."""
    d = graph.nodes.get(node)
    ports = getattr(d, "ports", None) if d else None
    if ports:
        return list(ports)
    return []


def propose_stubs(graph, completeness: dict) -> Proposal | None:
    """Stub every module the file set cannot resolve.

    The kernel already names them: `completeness()['unresolved']`. Stubbing is the
    standard way to get the rest of a graph to elaborate when vendor IP or a PDK is
    absent, and it is honest as long as the stubs are visibly empty.
    """
    unresolved = sorted(completeness.get("unresolved", []))
    if not unresolved:
        return None
    lines = [
        "// Generated by WENGOLD. These modules are instantiated in the file set but",
        "// not defined by it, so every result downstream of them is UNKNOWN.",
        "//",
        "// Each stub is EMPTY and returns X on its outputs. That is deliberate: a stub",
        "// that returned 0 would let a check pass for the wrong reason. Replace these",
        "// with real implementations, or add the real files to the file set.",
        "",
    ]
    for name in unresolved:
        ports = _port_names(graph, name)
        if ports:
            lines.append(f"module {name}({', '.join(ports)});")
            lines.append(f"  // TODO: real implementation — ports taken from the "
                         f"instantiation site")
            lines.append("endmodule")
        else:
            lines.append(f"module {name}();")
            lines.append("  // TODO: real implementation — port list not recoverable "
                         "from the graph")
            lines.append("endmodule")
        lines.append("")
    after = "\n".join(lines)
    return Proposal(
        id="stub-unresolved",
        title=f"Stub the {len(unresolved)} unresolved module(s)",
        rationale=(f"completeness() reports {len(unresolved)} module(s) instantiated "
                   f"but not defined in the file set, so results downstream of them "
                   f"are UNKNOWN by design"),
        path=STUB_FILE, diff=_diff(STUB_FILE, "", after), new_text=after,
        kind="create", facts={"unresolved": unresolved})


def propose_duplicate_exclusion(graph, root: str | Path) -> Proposal | None:
    """Propose a file list that excludes the duplicate copy of a module.

    When two files declare the same module the graph silently keeps one, and which
    one depends on file order. Excluding the copy makes that explicit instead of
    leaving it to chance.
    """
    dups = [n for n in graph.notes if "duplicate definition" in n]
    if not dups:
        return None
    # the note names the files: "`mod` is declared in A, B — ..."
    keep, drop = [], []
    for note in dups:
        try:
            tail = note.split("declared in", 1)[1].split("—", 1)[0]
            paths = [p.strip() for p in tail.split(",") if p.strip()]
        except IndexError:
            continue
        if len(paths) > 1:
            keep.append(paths[0])
            drop.extend(paths[1:])
    if not drop:
        return None
    files = sorted(set(keep))
    body = "\n".join(files) + "\n"
    lines = [
        "// WENGOLD file list: one copy of each duplicated module.",
        "// The duplicates below were excluded so that which definition elaborates",
        "// is a decision rather than an accident of file order.",
        "//",
        *[f"//   excluded: {d}" for d in sorted(set(drop))],
        "",
        body,
    ]
    after = "\n".join(lines)
    return Proposal(
        id="dedupe-filelist",
        title=f"Exclude {len(set(drop))} duplicate file(s) via a file list",
        rationale=(f"the graph reports {len(dups)} duplicate definition(s); it keeps "
                   f"one of each and which one depends on file order"),
        path="wengold.f", diff=_diff("wengold.f", "", after), new_text=after,
        kind="create", facts={"excluded": sorted(set(drop))})


def propose_all(graph, completeness: dict, root: str | Path) -> list[Proposal]:
    out = []
    for fn in (lambda: propose_stubs(graph, completeness),
               lambda: propose_duplicate_exclusion(graph, root)):
        try:
            p = fn()
        except Exception:
            p = None
        if p:
            out.append(p)
    return out
