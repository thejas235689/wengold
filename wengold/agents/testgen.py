"""Test generator: writes testbenches and assertions for open items.

Deterministic by default — it emits real, runnable cocotb and SVA from the
module's interface, so a first test exists with no model in the loop. When an
`llm` with a `complete(prompt)` method is supplied it is used instead, but the
output is still checked for the required shape before it is accepted.
"""
from __future__ import annotations

from dataclasses import dataclass

from ..graph.model import DesignGraph, NodeKind


@dataclass
class Port:
    name: str
    direction: str = "input"          # input | output | inout
    width: int = 1


_TB = '''"""cocotb testbench for {module} — generated by WENGOLD."""
import random

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import RisingEdge, Timer

CLK_PERIOD_NS = 10


@cocotb.test()
async def smoke(dut):
    """Drive the inputs, step the clock, and assert the outputs are not X."""
    random.seed({seed})
    {clk_start}
    {reset_start}
    outputs = {outputs}
    for _ in range({cycles}):
        {drive_inputs}
        {advance}
        for name, sig in outputs.items():
            assert sig.value.is_resolvable, f"{{name}} is X"
'''


class TestGen:
    __test__ = False          # not a pytest test class, despite the name

    def __init__(self, llm=None) -> None:
        self.llm = llm

    # ---- generation ---------------------------------------------------
    def cocotb_testbench(self, module: str, ports: list[Port], clock: str | None = None,
                         reset: str | None = None, seed: int = 0, cycles: int = 8) -> str:
        ins = [p for p in ports
               if p.direction in ("input", "inout") and p.name not in (clock, reset)]
        outs = [p for p in ports if p.direction == "output"]

        drive = "\n        ".join(
            f"dut.{p.name}.value = random.getrandbits({p.width})" for p in ins) or "pass"
        outputs = "{" + ", ".join(f'"{p.name}": dut.{p.name}' for p in outs) + "}"

        clk_start = "pass"
        advance = "await Timer(CLK_PERIOD_NS, units='ns')"
        if clock:
            clk_start = (f"cocotb.start_soon("
                         f"Clock(dut.{clock}, CLK_PERIOD_NS, units='ns').start())")
            advance = f"await RisingEdge(dut.{clock})"

        reset_start = "pass"
        if reset:
            reset_start = (f"dut.{reset}.value = 0\n"
                           f"    await Timer(CLK_PERIOD_NS * 2, units='ns')\n"
                           f"    dut.{reset}.value = 1")

        return _TB.format(module=module, seed=seed, cycles=cycles,
                          clk_start=clk_start, reset_start=reset_start,
                          drive_inputs=drive, advance=advance, outputs=outputs)

    def assertion(self, name: str, module: str, expression: str,
                  clock: str = "clk", reset: str = "rst_n") -> str:
        return (
            f"// generated by WENGOLD\n"
            f"module {name} (\n"
            f"    input logic {clock}, input logic {reset}\n"
            f");\n"
            f"    // bind into {module}\n"
            f"    a_{name}: assert property (@(posedge {clock}) disable iff (!{reset}) {expression});\n"
            f"endmodule\n"
        )

    def generate(self, target: str, kind: str = "cocotb", **kwargs):
        if self.llm is not None and hasattr(self.llm, "complete"):
            prompt = (f"Write a {kind} testbench for module {target} "
                      f"with ports {kwargs.get('ports')}.")
            text = self.llm.complete(prompt)
            if kind == "cocotb" and "async def" not in text:
                raise ValueError("model output is not a cocotb testbench")
            return text
        if kind == "cocotb":
            return self.cocotb_testbench(target, kwargs.get("ports", []),
                                         kwargs.get("clock"), kwargs.get("reset"),
                                         kwargs.get("seed", 0), kwargs.get("cycles", 8))
        if kind in ("sva", "assertion"):
            return self.assertion(target, kwargs.get("module", target),
                                  kwargs.get("expression", "1'b1"),
                                  kwargs.get("clock", "clk"), kwargs.get("reset", "rst_n"))
        raise ValueError(f"unknown test kind: {kind}")

    # ---- from the graph ----------------------------------------------
    def ports_from_graph(self, graph: DesignGraph, module: str) -> list[Port]:
        node = graph.nodes.get(module)
        if not node:
            return []
        return [Port(p["name"], p.get("direction", "input"), p.get("width", 1))
                for p in node.meta.get("ports", [])]

    def coverage_gaps(self, graph: DesignGraph) -> list[str]:
        """Coverage nodes with no test covering them."""
        covered = {e.src for e in graph.edges if e.kind.value == "covers"}
        return sorted(n.id for n in graph.nodes_of(NodeKind.COVERAGE) if n.id not in covered)
